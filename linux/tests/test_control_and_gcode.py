@unittest.skipIf(gantry_app is None, "gantry.app needs the GTK bindings")
class AppControlTests(unittest.TestCase):
    def _app(self, state=PrinterState.IDLE):
        app = gantry_app.Gantry.__new__(gantry_app.Gantry)
        app.printers = [Printer("X1", "X1C", "10.0.0.5", kind=PrinterKind.BAMBU),
                        Printer("O1", "Ender", "10.0.0.8", port=80, kind=PrinterKind.OCTOPRINT),
                        Printer("P1", "MK4", "10.0.0.9", port=80, kind=PrinterKind.PRUSA)]
        app.telemetry = {serial: Telemetry(state=state) for serial in ("X1", "O1", "P1")}
        app.sent_commands, app.sent_gcode, app.actions = [], [], []
        app.send_command = lambda serial, text: (app.sent_commands.append((serial, json.loads(text))), True)[1]
        app.send_gcode = lambda serial, text: (app.sent_gcode.append((serial, text)), True)[1]
        connection = SimpleNamespace(job_action=lambda action: app.actions.append(action) or True)
        app.connections = {"O1": connection, "P1": connection}
        app.detail_window = None
        return app

    def test_octoprint_jogs_homes_and_sets_fans_with_gcode(self):
        app = self._app()
        self.assertTrue(app.jog("O1", x=10))
        self.assertTrue(app.home("O1", "XY"))
        app.set_fan("O1", 1, 50)
        self.assertEqual(app.sent_gcode, [("O1", "G91\nG1 X10.00 F3000\nG90"), ("O1", "G28 X Y"), ("O1", "M106 S127")])

    def test_motion_is_refused_mid_print_and_on_printers_without_gcode(self):
        app = self._app(PrinterState.PRINTING)
        self.assertFalse(app.jog("O1", z=1))
        self.assertFalse(app.home("X1"))
        app.telemetry["P1"] = Telemetry(state=PrinterState.IDLE)
        self.assertFalse(app.jog("P1", x=1))
        self.assertEqual(app.sent_gcode + app.sent_commands, [])

    def test_bambu_that_wants_signed_commands_takes_no_motion(self):
        app = self._app()
        app.telemetry["X1"].command_signing_required = True
        self.assertFalse(app.accepts_gcode("X1"))
        self.assertFalse(app.home("X1"))
        app.telemetry["X1"].command_signing_required = False
        self.assertTrue(app.home("X1"))
        self.assertEqual(app.sent_commands[0][1]["print"]["param"], "G28\n")

    def test_print_actions_reach_every_brand(self):
        app = self._app(PrinterState.PRINTING)
        app.send_print_action("O1", "pause")
        app.send_print_action("P1", "stop")
        app.send_print_action("X1", "resume")
        deadline = time.time() + 2
        while len(app.actions) < 2 and time.time() < deadline:
            time.sleep(0.01)
        self.assertEqual(sorted(app.actions), ["pause", "stop"])
        self.assertEqual(app.sent_commands[0][1]["print"]["command"], "resume")

    def test_keys_over_the_panel(self):
        from gi.repository import Gdk
        self.assertEqual(key_move(Gdk.KEY_Left, False), (-1.0, 0.0, 0.0))
        self.assertEqual(key_move(Gdk.KEY_Up, True), (0.0, 10.0, 0.0))
        self.assertEqual(key_move(Gdk.KEY_Page_Down, False), (0.0, 0.0, -1.0))
        self.assertEqual(key_move(Gdk.KEY_h, False), "home")
        self.assertIsNone(key_move(Gdk.KEY_a, False))

    def test_jog_pad_rings(self):
        self.assertEqual(JogPad.hit(180, 180, 90, 90), (-1, 0))
        self.assertEqual(JogPad.hit(180, 180, 90, 40), (0, 1.0))       # inner ring, up: +Y 1 mm
        self.assertEqual(JogPad.hit(180, 180, 170, 90), (1, 10.0))     # outer ring, right: +X 10 mm
        self.assertIsNone(JogPad.hit(180, 180, 2, 2))

    def test_send_dialog_lines(self):
        lines = send_lines({"seconds": 3723, "filaments": [{"material": "PETG", "grams": 12.3}]}, "AMS")
        self.assertEqual(len(lines), 4)
        self.assertIn("1 h 02 min", lines[0])
        self.assertIn("PETG 12 g", lines[1])


